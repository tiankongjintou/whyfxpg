def test_generate_pg_ddl_contains_columns_and_pk() -> None:
    columns = [
        {"cid": 0, "name": "log_id", "type": "INTEGER", "notnull": 1,
         "dflt_value": None, "pk": 1, "autoincrement": True},
        {"cid": 1, "name": "source_id", "type": "TEXT", "notnull": 0,
         "dflt_value": None, "pk": 0},
        {"cid": 2, "name": "status", "type": "TEXT", "notnull": 0,
         "dflt_value": "'pending'", "pk": 0},
    ]
    ddl = generate_pg_ddl("crawl_logs", columns)
    assert "CREATE TABLE IF NOT EXISTS \"crawl_logs\"" in ddl
    assert '"log_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in ddl
    assert '"source_id" TEXT' in ddl
    assert "DEFAULT ('pending')" in ddl


def test_list_tables_excludes_sqlite_internal() -> None:
    conn = sqlite3.connect(":memory:")
    conn.execute("CREATE TABLE business (id INTEGER PRIMARY KEY)")
    conn.execute("CREATE TABLE other_business (id INTEGER PRIMARY KEY)")
    tables = list_tables(conn)
    assert tables == ["business", "other_business"]
    assert sqlite_table_info(conn, "business")[0]["name"] == "id"
    conn.close()
