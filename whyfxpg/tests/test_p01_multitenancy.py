def test_get_database_url_defaults_to_sqlite(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("DATABASE_URL", raising=False)
    assert get_database_url() == str(DEFAULT_DB_PATH)


def test_get_database_url_reads_postgres_env(monkeypatch: pytest.MonkeyPatch) -> None:
    url = "postgresql://user:pass@db:5432/whyfxpg"
    monkeypatch.setenv("DATABASE_URL", url)
    assert get_database_url() == url


@pytest.mark.parametrize(
    ("url", "expected"),
    [
        ("postgresql://u:p@h/db", True),
        ("postgres://u:p@h/db", True),
        ("sqlite:///x.db", False),
        ("/plain/path.db", False),
        ("", False),
    ],
)
def test_is_postgres_url(url: str, expected: bool) -> None:
    assert is_postgres_url(url) is expected


