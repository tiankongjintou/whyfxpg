def _run_alembic_upgrade(db_path: Path) -> None:
    from alembic.config import Config

    from alembic import command

    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("sqlalchemy.url", f"sqlite:///{db_path}")
    command.upgrade(cfg, "head")


def test_alembic_0001_creates_multitenancy_schema(tmp_path: Path) -> None:
    """0001 迁移在空库上创建 accounts + 租户列 + 索引。"""
    db = tmp_path / "p01.db"
    _run_alembic_upgrade(db)

    engine = create_engine(f"sqlite:///{db}")
    insp = inspect(engine)

    # accounts 表（AC-2）
    assert "accounts" in insp.get_table_names()
    acct_cols = {c["name"] for c in insp.get_columns("accounts")}
    assert acct_cols == {
        "id", "company_name", "plan_type", "api_key_hash",
        "api_key_prefix", "monthly_quota", "created_at", "status",
    }

    # risk_events 加 account_id 外键 + created_at（AC-3）
    re_cols = {c["name"] for c in insp.get_columns("risk_events")}
    assert "account_id" in re_cols
    assert "created_at" in re_cols

    # alert_records 加 account_id 外键（AC-4）
    al_cols = {c["name"] for c in insp.get_columns("alert_records")}
    assert "account_id" in al_cols

    # 3 个索引（AC-5）
    indexes = {i["name"] for i in insp.get_indexes("risk_events")}
    assert {
        "idx_risk_events_account",
        "idx_risk_events_manufacturer",
        "idx_risk_events_created",
    } <= indexes
    engine.dispose()


def test_alembic_0001_downgrade_removes_tenant_columns(tmp_path: Path) -> None:
    """downgrade 应删除 account_id/索引/accounts 表。"""
    from alembic.config import Config

    from alembic import command

    db = tmp_path / "p01_down.db"
    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("sqlalchemy.url", f"sqlite:///{db}")
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")

    engine = create_engine(f"sqlite:///{db}")
    insp = inspect(engine)
    assert "accounts" not in insp.get_table_names()
    re_cols = {c["name"] for c in insp.get_columns("risk_events")}
    assert "account_id" not in re_cols
    engine.dispose()


